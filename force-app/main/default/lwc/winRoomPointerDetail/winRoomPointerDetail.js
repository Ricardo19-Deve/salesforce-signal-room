import { LightningElement, api } from "lwc";
import { NavigationMixin } from "lightning/navigation";
import getPointer from "@salesforce/apex/WinRoomController.getPointer";
import decidePointer from "@salesforce/apex/WinRoomController.decidePointer";
import convertToOpportunity from "@salesforce/apex/WinRoomController.convertToOpportunity";
import enrichWithAI from "@salesforce/apex/WinRoomController.enrichWithAI";
import saveCommitment from "@salesforce/apex/WinRoomController.saveCommitment";
import updateCommitment from "@salesforce/apex/WinRoomController.updateCommitment";
import {
    REJECTION_REASONS, money, formatDate, todayIso, priorityClass, statusClass, reduceErrors
} from "c/winRoomUtils";

export default class WinRoomPointerDetail extends NavigationMixin(LightningElement) {
    _pointerId;
    p;
    error;
    loading = false;
    busy = false;
    aiBusy = false;
    mode = null; // reject | convert
    rejectReason = "";
    rejectComment = "";
    convertAmount;
    convertClose = todayIso(90);
    newAction = "";
    newDue = todayIso(7);

    @api
    get pointerId() {
        return this._pointerId;
    }
    set pointerId(v) {
        this._pointerId = v;
        this.mode = null;
        this.load();
    }

    async load() {
        if (!this._pointerId) return;
        this.loading = true;
        try {
            this.p = await getPointer({ pointerId: this._pointerId });
            this.convertAmount = this.p.value;
            this.error = undefined;
        } catch (e) {
            this.error = reduceErrors(e);
        } finally {
            this.loading = false;
        }
    }

    // ---------------------------------------------------------------- view model
    get ready() {
        return !!this.p;
    }
    get valueText() {
        return money(this.p.value);
    }
    get priorityCls() {
        return priorityClass(this.p.priority);
    }
    get statusCls() {
        return statusClass(this.p.status);
    }
    get dueText() {
        return formatDate(this.p.dueDate);
    }
    get isNew() {
        return this.p.status === "New";
    }
    get isAccepted() {
        return this.p.status === "Accepted";
    }
    get isClosed() {
        return this.p.status === "Rejected" || this.p.status === "Expired";
    }
    get isConverted() {
        return this.p.status === "Converted";
    }
    get canDecide() {
        return this.isNew || this.isAccepted;
    }
    get rejecting() {
        return this.mode === "reject";
    }
    get converting() {
        return this.mode === "convert";
    }
    get reasonOptions() {
        return REJECTION_REASONS.map((r) => ({ label: r, value: r }));
    }
    get facts() {
        const f = (this.p.evidence && this.p.evidence.facts) || {};
        return Object.keys(f).map((k) => ({ key: k, label: k, value: f[k] }));
    }
    get hasChart() {
        return this.p.evidence && (this.p.evidence.series || []).length > 0;
    }
    get chartMonths() {
        return this.p.evidence.months;
    }
    get chartSeries() {
        return this.p.evidence.series;
    }
    get playbook() {
        return (this.p.nextBestAction || "").split(/\.\s+/).filter((s) => s.trim()).map((s, i) => ({ key: `pb${i}`, text: s.replace(/\.$/, "") + "." }));
    }
    get ai() {
        return this.p.aiInsight;
    }
    get hasAi() {
        return !!this.ai;
    }
    get aiLists() {
        if (!this.ai) return [];
        const lists = [
            ["nextBestActions", "Next best actions"],
            ["talkingPoints", "Talking points"],
            ["discoveryQuestions", "Questions to validate with the customer"],
            ["risks", "Why this could be wrong"]
        ];
        return lists
            .filter(([k]) => Array.isArray(this.ai[k]) && this.ai[k].length)
            .map(([k, label]) => ({ key: k, label, items: this.ai[k].map((t, i) => ({ key: `${k}${i}`, text: t })) }));
    }
    get aiNote() {
        if (!this.ai) return "";
        if (this.ai.aiGenerated) return `Generated by AI on ${formatDate(this.p.aiGeneratedOn)} - review before using with customers.`;
        return this.ai.note || this.ai.error || "Rule-based summary.";
    }
    get aiButtonLabel() {
        return this.hasAi ? "Regenerate" : "Generate AI insight";
    }
    get commitments() {
        return (this.p.commitments || []).map((c) => ({
            ...c,
            due: formatDate(c.Due_Date__c),
            cls: statusClass(c.Status__c),
            ownerName: c.Owner_User__r ? c.Owner_User__r.Name : "",
            isOpen: c.Status__c === "Open"
        }));
    }
    get hasCommitments() {
        return this.commitments.length > 0;
    }
    get decisionText() {
        if (!this.p.decidedBy) return "";
        return `${this.p.status} by ${this.p.decidedBy} on ${formatDate(this.p.decidedOn)}${this.p.rejectionReason ? " - " + this.p.rejectionReason : ""}${this.p.decisionComment ? ": " + this.p.decisionComment : ""}`;
    }

    // ---------------------------------------------------------------- actions
    close() {
        this.dispatchEvent(new CustomEvent("close"));
    }
    openAccount() {
        this.dispatchEvent(new CustomEvent("openaccount", { detail: { accountId: this.p.accountId } }));
    }
    openOpportunity() {
        this[NavigationMixin.Navigate]({
            type: "standard__recordPage",
            attributes: { recordId: this.p.opportunityId, objectApiName: "Opportunity", actionName: "view" }
        });
    }

    async run(fn) {
        this.busy = true;
        try {
            const result = await fn();
            if (result && result.id) {
                this.p = result;
            } else {
                await this.load();
            }
            this.mode = null;
            this.error = undefined;
            this.dispatchEvent(new CustomEvent("changed"));
        } catch (e) {
            this.error = reduceErrors(e);
        } finally {
            this.busy = false;
        }
    }

    accept() {
        this.run(() => decidePointer({ pointerId: this.p.id, decision: "Accepted", reason: null, comment: null }));
    }
    reopen() {
        this.run(() => decidePointer({ pointerId: this.p.id, decision: "New", reason: null, comment: null }));
    }
    startReject() {
        this.mode = "reject";
    }
    startConvert() {
        this.mode = "convert";
    }
    cancelMode() {
        this.mode = null;
    }
    handleReason(e) {
        this.rejectReason = e.detail.value;
    }
    handleComment(e) {
        this.rejectComment = e.target.value;
    }
    confirmReject() {
        this.run(() =>
            decidePointer({ pointerId: this.p.id, decision: "Rejected", reason: this.rejectReason, comment: this.rejectComment })
        );
    }
    handleAmount(e) {
        this.convertAmount = e.target.value;
    }
    handleClose(e) {
        this.convertClose = e.target.value;
    }
    confirmConvert() {
        this.run(() =>
            convertToOpportunity({
                pointerId: this.p.id,
                amount: this.convertAmount ? Number(this.convertAmount) : null,
                closeDate: this.convertClose || null
            })
        );
    }
    async generateAi() {
        this.aiBusy = true;
        try {
            this.p = await enrichWithAI({ pointerId: this.p.id });
            this.error = undefined;
        } catch (e) {
            this.error = reduceErrors(e);
        } finally {
            this.aiBusy = false;
        }
    }
    handleNewAction(e) {
        this.newAction = e.target.value;
    }
    handleNewDue(e) {
        this.newDue = e.target.value;
    }
    async addCommitment() {
        if (!this.newAction || !this.newAction.trim()) return;
        await this.run(() =>
            saveCommitment({
                commitmentJson: JSON.stringify({ pointerId: this.p.id, action: this.newAction, dueDate: this.newDue })
            })
        );
        this.newAction = "";
    }
    markDone(e) {
        const id = e.currentTarget.dataset.id;
        this.run(() => updateCommitment({ commitmentId: id, status: "Done", outcome: null }));
    }
}
